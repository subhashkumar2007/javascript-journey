


// ------------------------------* Number Classification *---------------------------------------------

const num = 105;

// -------------* Positive , Negative, Zero *----------


if(num > 0){
    console.log("Positive");
}else if (num < 0){
    console.log("Negative");
}else{
    console.log("Zero");
}

// -----------* Even OR Odd *--------

if(num % 2 === 0){
    console.log("Even");
}else{
    console.log("Odd");
}

// ------------- greater than 100 , less than 100, equal to 100 *--------------------

if(num > 100){
    console.log("Greater than 100");
}else if (num < 100){
    console.log("Less than 100");
}else{
    console.log("equal to 100");
}


