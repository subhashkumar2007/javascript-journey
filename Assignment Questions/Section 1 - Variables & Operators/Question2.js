

// ----------------------------* Swap Two Numbers *-------------------------------


let a = 10;
let b = 20;

console.log("Before swapping:");
console.log("a = " + a);
console.log("b = " + b);

// Third variable se swap

let temp = a;
a = b;
b = temp;

console.log("\nAfter swapping:");
console.log("a = " + a);
console.log("b = " + b);